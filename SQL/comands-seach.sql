-- Filtrar dependentes
SELECT
    C.NOME AS NOME_COLABORADOR,
    D.NOME AS NOME_DEPENDENTE,
    D.DATA_NASCIMENTO
FROM
    DEPENDENTE D
    INNER JOIN COLABORADOR C ON C.MATRICULA = D.COLABORADOR
WHERE
    D.NOME LIKE '%h%'
    OR TO_CHAR(D.DATA_NASCIMENTO, 'MM') IN (
        '04',
        '05',
        '06'
    )
ORDER BY
    C.NOME,
    D.NOME;

-- Listar colaborador com maior salário
SELECT
    NOME,
    SALARIO
FROM
    COLABORADOR
WHERE
    ROWNUM = 1
ORDER BY
    SALARIO DESC;

-- Relatório de senioridade
SELECT
    MATRICULA,
    NOME,
    SALARIO,
    CASE
        WHEN SALARIO <= 3000 THEN 'Júnior'
        WHEN SALARIO BETWEEN 3000.01
        AND 6000 THEN 'Pleno'
        WHEN SALARIO BETWEEN 6000.01
        AND 20000 THEN 'Sênior'
        ELSE 'Corpo diretor'
    END AS SENIORIDADE
FROM
    COLABORADOR
ORDER BY
    SENIORIDADE,
    NOME;

-- Listar quantidade de colaboradores em projetos
SELECT
    D.NOME,
    P.NOME,
    COUNT(C.MATRICULA) AS QUANTIDADE_COLABORADORES
FROM
    PROJETO P
    INNER JOIN ATRIBUICAO A ON P.ID = A.PROJETO
    INNER JOIN COLABORADOR C ON A.COLABORADOR = C.MATRICULA
    INNER JOIN DEPARTAMENTO D ON D.SIGLA = C.DEPARTAMENTO
GROUP BY
    D.NOME,
    P.NOME
ORDER BY
    D.NOME,
    P.NOME;

-- Listar colaboradores com mais dependentes
SELECT
    C.NOME,
    COUNT(D.COLABORADOR) AS QUANTIDADE_DEPENDENTES
FROM
    COLABORADOR C
    INNER JOIN DEPENDENTE D ON C.MATRICULA = D.COLABORADOR
GROUP BY
    C.NOME
HAVING
    COUNT(D.COLABORADOR) > 1
ORDER BY
    QUANTIDADE_DEPENDENTES DESC,
    C.NOME;

-- Relatório analítico de equipes
SELECT
    D.NOME AS DEPARTAMENTO,
    CH.NOME AS CHEFE,
    CO.NOME AS COLABORADOR,
    PR.NOME AS PROJETO,
    PA.NOME AS PAPEL,
    T.NUMERO AS TELEFONE,
    DEP.NOME AS DEPENDENTE
FROM
    ATRIBUICAO A
    INNER JOIN PROJETO PR ON A.PROJETO = PR.ID
    INNER JOIN PAPEL PA ON A.PAPEL = PA.ID
    INNER JOIN COLABORADOR CO ON A.COLABORADOR = CO.MATRICULA
    INNER JOIN DEPARTAMENTO D ON CO.DEPARTAMENTO = D.SIGLA
    INNER JOIN COLABORADOR CH ON D.CHEFE = CH.MATRICULA
    INNER JOIN TELEFONE_COLABORADOR T ON CO.MATRICULA = T.COLABORADOR
    INNER JOIN DEPENDENTE DEP ON CO.MATRICULA = DEP.COLABORADOR
ORDER BY
    PROJETO,
    COLABORADOR,
    DEPENDENTE;

-- Listar faixa etária dos dependentes
SELECT
    CPF,
    NOME,
    TO_CHAR(DATA_NASCIMENTO, 'DD/MM/YYYY') AS "DATA DE NASCIMENTO",
    PARENTESCO,
    COLABORADOR,
    TRUNC(MONTHS_BETWEEN(SYSDATE, DATA_NASCIMENTO) / 12) AS IDADE,
    CASE
        WHEN TRUNC(MONTHS_BETWEEN(SYSDATE, DATA_NASCIMENTO) / 12) < 18 THEN 'Menor de idade'
        ELSE 'Maior de idade'
    END AS "FAIXA ETÁRIA"
FROM
    DEPENDENTE
ORDER BY
    COLABORADOR,
    NOME;

-- Paginar listagem de colaboradores
-- Relatório de plano de saúde
SELECT
    C.MATRICULA,
    C.NOME,
    C.SALARIO,
    CASE
        WHEN C.SALARIO <= 3000 THEN 'Júnior'
        WHEN C.SALARIO BETWEEN 3000.01
        AND 6000 THEN 'Pleno'
        WHEN C.SALARIO BETWEEN 6000.01
        AND 20000 THEN 'Sênior'
        ELSE 'Corpo diretor'
    END AS SENIORIDADE,
    CASE
        WHEN SALARIO <= 3000 THEN 0.001 * C.SALARIO
        WHEN SALARIO BETWEEN 3000.01
        AND 6000 THEN 0.002 * C.SALARIO
        WHEN SALARIO BETWEEN 6000.01
        AND 20000 THEN 0.003 * C.SALARIO
        ELSE 0.005 * C.SALARIO
    END AS PERCENTUAL_SAUDE
FROM
    COLABORADOR C
    INNER JOIN DEPENDENTE D ON C.MATRICULA = D.COLABORADOR
GROUP BY
    C.NOME;